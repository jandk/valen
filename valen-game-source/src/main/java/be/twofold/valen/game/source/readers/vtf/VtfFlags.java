package be.twofold.valen.game.source.readers.vtf;

import wtf.reversed.toolbox.util.*;

import java.util.*;

public enum VtfFlags implements FlagEnum {
    TEXTUREFLAGS_POINTSAMPLE(0x00000001),
    TEXTUREFLAGS_TRILINEAR(0x00000002),
    TEXTUREFLAGS_CLAMPS(0x00000004),
    TEXTUREFLAGS_CLAMPT(0x00000008),
    TEXTUREFLAGS_ANISOTROPIC(0x00000010),
    TEXTUREFLAGS_HINT_DXT5(0x00000020),
    TEXTUREFLAGS_SRGB(0x00000040),
    TEXTUREFLAGS_NORMAL(0x00000080),
    TEXTUREFLAGS_NOMIP(0x00000100),
    TEXTUREFLAGS_NOLOD(0x00000200),
    TEXTUREFLAGS_ALL_MIPS(0x00000400),
    TEXTUREFLAGS_PROCEDURAL(0x00000800),
    // These are automatically generated by vtex from the texture data.
    TEXTUREFLAGS_ONEBITALPHA(0x00001000),
    TEXTUREFLAGS_EIGHTBITALPHA(0x00002000),
    // newer flags from the *.txt config file
    TEXTUREFLAGS_ENVMAP(0x00004000),
    TEXTUREFLAGS_RENDERTARGET(0x00008000),
    TEXTUREFLAGS_DEPTHRENDERTARGET(0x00010000),
    TEXTUREFLAGS_NODEBUGOVERRIDE(0x00020000),
    TEXTUREFLAGS_SINGLECOPY(0x00040000),
    TEXTUREFLAGS_UNUSED_00080000(0x00080000),
    TEXTUREFLAGS_UNUSED_00100000(0x00100000),
    TEXTUREFLAGS_UNUSED_00200000(0x00200000),
    TEXTUREFLAGS_UNUSED_00400000(0x00400000),
    TEXTUREFLAGS_NODEPTHBUFFER(0x00800000),
    TEXTUREFLAGS_UNUSED_01000000(0x01000000),
    TEXTUREFLAGS_CLAMPU(0x02000000),
    TEXTUREFLAGS_VERTEXTEXTURE(0x04000000), // Useable as a vertex texture
    TEXTUREFLAGS_SSBUMP(0x08000000),
    TEXTUREFLAGS_UNUSED_10000000(0x10000000),
    // Clamp to border color on all texture coordinates
    TEXTUREFLAGS_BORDER(0x20000000),
    TEXTUREFLAGS_UNUSED_40000000(0x40000000),
    TEXTUREFLAGS_UNUSED_80000000(0x80000000),
    ;

    private final int value;

    VtfFlags(int value) {
        this.value = value;
    }

    public static Set<VtfFlags> fromValue(int value) {
        return FlagEnum.fromValue(VtfFlags.class, value);
    }

    @Override
    public int value() {
        return value;
    }
}
